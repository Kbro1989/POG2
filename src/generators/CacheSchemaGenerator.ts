import { existsSync, writeFileSync, mkdirSync } from 'fs';
import { join } from 'path';
import { createLogger } from '../utils/logger.js';
import { getrsmvBetaCachePath, resolveSovereignPath } from '../utils/SovereignPathResolver.js';
import { fileURLToPath } from 'url';

const logger = createLogger('CacheSchemaGenerator');

// List of critical appearance-related enums to auto-generate
const ENUM_TARGETS = [
    { id: 6796, name: 'FemaleHairStyles', desc: 'Female hairstyle index to name mapping' },
    { id: 16883, name: 'MaleHairStyles', desc: 'Male hairstyle index to name mapping' },
    { id: 17158, name: 'BeardStyles', desc: 'Beard index to morphology model ID mapping' },
    { id: 15477, name: 'BeardNames', desc: 'Beard index to name mapping' }
];

export async function generateAppearanceEnums(cachePath: string): Promise<string> {
    if (!cachePath || !existsSync(cachePath)) {
        throw new Error(`Cache path does not exist: ${cachePath}`);
    }

    try {
        // Dynamic imports to load decoupled rsmv safely
        const { GameCacheLoader } = await import('rsmv/cache/sqlite.js');
        const { cacheMajors } = await import('rsmv/constants.js');
        const { parse } = await import('rsmv/opdecoder.js');

        const loader = new GameCacheLoader(cachePath);
        let tsContent = `/**
 * Auto-generated by Sovereign POG2 Cache Schema-to-Code Generator.
 * Generated At: ${new Date().toISOString()}
 * Cache Substrate Path: ${cachePath}
 */

`;

        for (const target of ENUM_TARGETS) {
            try {
                const buf = await loader.getFileById(cacheMajors.enums, target.id);
                const decoded = parse.enums.read(buf, {
                    getDecodeArgs() {
                        return { clientVersion: 1000 };
                    }
                } as any);

                // Get values array
                const values: [number, any][] = 
                    decoded.stringArrayValue2?.values || 
                    decoded.intArrayValue2?.values || 
                    [];

                tsContent += `/**
 * ${target.desc}
 * Enum ID: ${target.id}
 */
export const ${target.name}: Record<number, ${target.id === 17158 ? 'number' : 'string'}> = {
`;

                for (const [key, val] of values) {
                    const formattedVal = typeof val === 'string' ? JSON.stringify(val) : val;
                    tsContent += `    ${key}: ${formattedVal},\n`;
                }

                tsContent += `};\n\n`;
                logger.info({ enumId: target.id, name: target.name, entries: values.length }, 'Successfully parsed cache enum.');
            } catch (e) {
                logger.warn({ enumId: target.id, name: target.name, err: e }, 'Failed to parse enum, generating empty mapping fallback.');
                tsContent += `/**
 * FALLBACK: ${target.desc} (Failed to load from cache)
 * Enum ID: ${target.id}
 */
export const ${target.name}: Record<number, any> = {};\n\n`;
            }
        }

        const currentDir = join(fileURLToPath(import.meta.url), '..');
        const outDir = join(currentDir, '../generated/cache-schemas');
        if (!existsSync(outDir)) {
            mkdirSync(outDir, { recursive: true });
        }

        const outFile = join(outDir, 'AppearanceEnums.ts');
        writeFileSync(outFile, tsContent, 'utf8');
        logger.info({ path: outFile }, 'Appearance enums TypeScript file written successfully.');
        return outFile;
    } catch (e) {
        logger.error({ err: e }, 'Schema-to-Code generation failed.');
        throw e;
    }
}
