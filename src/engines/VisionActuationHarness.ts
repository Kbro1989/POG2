import { createRequire } from 'module';
const require = createRequire(import.meta.url);
import { createLogger } from '../utils/logger.js';
import { PuppeteerEye } from '../vision/PuppeteerEye.js';
import { ChromanumberEngine } from '../engines/ChromanumberEngine.js';
import { ShaderInjector } from '../vision/ShaderInjector.js';
import { RSMVController } from '../vision/RSMVController.js';
import { SpatialVisionEngine } from '../engines/SpatialVisionEngine.js';
import { getPedagogyPath, resolveSovereignPath } from '../utils/SovereignPathResolver.js';
import { readFileSync, readdirSync, existsSync, writeFileSync } from 'fs';
import { join } from 'path';
import type { Result, ActuationIntent, ActuationResult } from '../core/models.js';

const logger = createLogger('VisionActuationHarness');

/**
 * VisionActuationHarness â€” End-to-End Perception-Action Loop Harness.
 * 1. Observes substrate via PuppeteerEye.
 * 2. Processes vision/intent via ChromanumberEngine.
 * 3. Actuates changes via ShaderInjector or RSMVController.
 */
export class VisionActuationHarness {
    private eye: PuppeteerEye;
    private engine: ChromanumberEngine;
    private spatialVision: SpatialVisionEngine;
    private injector: ShaderInjector;
    private rsmv: RSMVController;
    private hudSubstrates: any[] = [];

    constructor(engine: ChromanumberEngine, spatialVision: SpatialVisionEngine) {
        this.engine = engine;
        this.spatialVision = spatialVision;
        this.eye = new PuppeteerEye();
        this.injector = new ShaderInjector();
        this.rsmv = RSMVController.getInstance();
        this.loadHUDSubstrates();
    }

    /**
     * Load pedagogical HUD candidates from the Sovereign drive.
     */
    private loadHUDSubstrates(): void {
        try {
            const pedagogyPath = getPedagogyPath();
            if (existsSync(pedagogyPath)) {
                const files = readdirSync(pedagogyPath);
                const hudFiles = files.filter(f => f.startsWith('GROUP_PRINCIPLE_HUD_CANDIDATE_'));

                for (const file of hudFiles) {
                    const data = JSON.parse(readFileSync(join(pedagogyPath, file), 'utf8'));
                    this.hudSubstrates.push(data);
                }
                logger.info({ count: this.hudSubstrates.length }, 'Loaded pedagogical HUD substrates.');
            }
        } catch (err) {
            logger.warn({ err }, 'Failed to load HUD substrates.');
        }
    }

    /**
     * Run a single perception-action cycle.
     */
    public async runCycle(url: string, prompt: string): Promise<Result<ActuationResult>> {
        logger.info({ url, prompt }, 'Starting Perception-Action Cycle');

        try {
            // 1. sensory Perception (DOM + Screenshot)
            const capture = await this.eye.domInspect(url);
            if (!capture.ok) return capture as any;

            logger.info({ screenshot: capture.value.screenshot }, 'Perception captured');

            // 1.5 Deterministic Color Detection (Phase 15.5)
            const colorsRes = await this.eye.getDeterministicColors(capture.value.screenshot);
            const dominantColors = colorsRes.ok ? colorsRes.value.map(c => c.hex) : [];
            if (dominantColors.length > 0) {
                logger.info({ dominantColors }, 'Deterministic colors detected from substrate');
            }

            // 2. Spatial UI Analysis (Phase 26)
            logger.info('Performing Spatial UI Analysis for HUD forensics');
            const spatialRes = await this.spatialVision.observe({
                intent: 'ui_analysis',
                target: capture.value.screenshot,
                includeScreenshot: false
            });

            if (spatialRes.ok && spatialRes.value.data?.spatialMap) {
                const map = spatialRes.value.data.spatialMap;
                logger.info({ regions: map.regions?.length }, 'Spatial HUD regions mapped');

                // Save mapping results to D:\ sovereign learning substrate
                const learningPath = resolveSovereignPath(join('learning', `hud_mapping_${Date.now()}.json`));
                writeFileSync(learningPath, JSON.stringify({
                    timestamp: Date.now(),
                    url,
                    spatialMap: map,
                    pedagogyMatches: this.hudSubstrates.length // Placeholder for match logic
                }, null, 2));
            }

            // 3. Intent Generation
            const forgeRes = await this.engine.forgeComponent(prompt, { spatialRes }, dominantColors);
            if (!forgeRes.ok) return forgeRes as any;

            const intent = forgeRes.value.actuation;
            if (!intent) {
                return { ok: true, value: { success: false, details: 'No actuation intent generated by engine.' } };
            }

            // 4. Actuation Execution
            logger.info({ action: intent.action }, 'Executing Actuation Intent');
            return await this.executeActuation(intent);

        } catch (err) {
            logger.error({ err }, 'Harness cycle failed');
            return { ok: false, error: err as Error };
        }
    }

    /**
     * Dispatch intent to the appropriate actuator.
     */
    private async executeActuation(intent: ActuationIntent): Promise<Result<ActuationResult>> {
        switch (intent.action) {
            case 'mutate_shader':
                return await this.injector.injectColor(intent.target, intent.parameters.code);

            case 'rsmv_control':
                return await this.rsmv.viewModel(intent.parameters.modelId);

            case 'actuate_hud':
                // High-fidelity HUD interaction (Mocked to click via Puppeteer in production)
                logger.info({ widgetId: intent.parameters.widgetId }, 'Actuating HUD Widget');
                return { ok: true, value: { success: true, details: `Actuated HUD Widget ${intent.parameters.widgetId}` } };

            default:
                return { ok: false, error: new Error(`Unsupported actuation action: ${intent.action}`) };
        }
    }

    /**
     * Graceful shutdown of sensory components.
     */
    public async shutdown(): Promise<void> {
        await this.eye.sleep();
        logger.info('Harness shutdown complete.');
    }
}

