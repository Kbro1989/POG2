import { type Result, type Lesson, ok, err } from '../../core/models.js';
import { ModelClient } from '../../clients/ModelClient.js';
import { GHOST_LIMB_APP_TSX, SOVEREIGN_TAILWIND_CONFIG, SOVEREIGN_MAIN_CSS } from '../../utils/SovereignUI.js';
import { existsSync, mkdirSync, writeFileSync, readdirSync, lstatSync, copyFileSync, readFileSync } from 'fs';
import { join, resolve, dirname } from 'path';
import { fileURLToPath } from 'url';
import { HexagramManager } from '../../routing/HexagramManager.js';
import { resolvePackagePath } from '../../utils/SovereignPathResolver.js';

const logger = createLogger('WebAppForgeLimb');

import { SOVEREIGN_COMPONENTS } from '../../utils/SovereignLibrary.js';
import { createLogger } from "../../utils/logger.js";

export interface AppBlueprint {
    name: string;
    features: string[];
    stack: 'react-vite' | 'nextjs-tailwind' | 'cloudflare-template' | 'synthetic';
    template?: string;
    decision_reasoning?: string;
}

export class WebAppForgeLimb {
    private readonly templatesPath: string;

    constructor(
        private readonly client: ModelClient,
        private readonly hexagram: HexagramManager = HexagramManager.getInstance()
    ) {
        // Resources are stored in dist/resources relative to the package root
        this.templatesPath = resolvePackagePath('dist', 'resources', 'cloudflare-templates');
    }

    public listAvailableTemplates(): string[] {
        if (!existsSync(this.templatesPath)) return [];
        const templatesJson = join(this.templatesPath, 'templates.json');
        if (!existsSync(templatesJson)) return [];
        try {
            const data = JSON.parse(readFileSync(templatesJson, 'utf8'));
            return Object.keys(data.templates);
        } catch {
            // Fallback to directory listing if JSON fails
            return readdirSync(this.templatesPath).filter(f =>
                lstatSync(join(this.templatesPath, f)).isDirectory() && !f.startsWith('.')
            );
        }
    }

    public async scaffoldFromTemplate(templateName: string, targetPath: string): Promise<Result<string>> {
        const sourcePath = join(this.templatesPath, templateName);
        if (!existsSync(sourcePath)) {
            return { ok: false, error: new Error(`Template not found: ${templateName}`) };
        }

        logger.info({ templateName, targetPath }, 'Scaffolding from Cloudflare template');

        try {
            this.copyRecursiveSync(sourcePath, targetPath);
            return ok(targetPath);
        } catch (err) {
            return { ok: false, error: err as Error };
        }
    }

    private copyRecursiveSync(src: string, dest: string) {
        if (!existsSync(dest)) mkdirSync(dest, { recursive: true });
        const entries = readdirSync(src);
        for (const entry of entries) {
            const srcPath = join(src, entry);
            const destPath = join(dest, entry);
            if (lstatSync(srcPath).isDirectory()) {
                this.copyRecursiveSync(srcPath, destPath);
            } else {
                copyFileSync(srcPath, destPath);
            }
        }
    }

    public async scaffoldProject(blueprint: AppBlueprint, targetPath: string): Promise<Result<string>> {
        if (blueprint.stack === 'cloudflare-template' && blueprint.template) {
            return this.scaffoldFromTemplate(blueprint.template, targetPath);
        }

        if (blueprint.stack === 'synthetic') {
            return this.forgeSyntheticApp(blueprint, targetPath);
        }

        logger.info({ blueprint, targetPath }, 'Scaffolding generative WebApp project');

        if (!existsSync(targetPath)) {
            mkdirSync(targetPath, { recursive: true });
        }

        try {
            const srcDir = join(targetPath, 'src');
            if (!existsSync(srcDir)) mkdirSync(srcDir, { recursive: true });

            writeFileSync(join(targetPath, 'tailwind.config.ts'), SOVEREIGN_TAILWIND_CONFIG);
            writeFileSync(join(srcDir, 'index.css'), SOVEREIGN_MAIN_CSS);
            writeFileSync(join(srcDir, 'App.tsx'), GHOST_LIMB_APP_TSX(blueprint.name, blueprint.features));

            writeFileSync(join(targetPath, 'INTENT_MANIFEST.md'),
                `# Intent Manifest: ${blueprint.name}\n\n` +
                `Generated by POG2 WebApp Forge.\n\n` +
                `## Features\n${blueprint.features.map(f => `- ${f}`).join('\n')}\n\n` +
                `## Cognitive Layer\n${blueprint.decision_reasoning || 'Ghost Limb Fallback Active.'}`
            );

            return ok(targetPath);
        } catch (err) {
            return { ok: false, error: err as Error };
        }
    }

    public async handleDigestComponent(args: Record<string, any>): Promise<Result<string>> {
        const projectDir = args.projectDir as string;
        const componentName = args.componentName as string;
        const description = (args.description as string) || '';
        const componentsDir = join(projectDir, 'src', 'components');
        const componentPath = join(componentsDir, `${componentName}.tsx`);

        if (!existsSync(componentsDir)) {
            mkdirSync(componentsDir, { recursive: true });
        }

        logger.info({ componentName }, 'Digesting UI component pattern');

        // Check Library First (Instant Absorption)
        const libraryKey = componentName.toUpperCase();
        const sovereignComponents = SOVEREIGN_COMPONENTS as Record<string, string>;
        if (sovereignComponents[libraryKey]) {
            const code = sovereignComponents[libraryKey];
            writeFileSync(componentPath, code);
            return ok(`Instantly digested ${componentName} from Sovereign Library.`);
        }

        // Tier 2: Neural Forge Distillation
        const uiPrompt = `Generate a high-fidelity, production-ready React component (Tailwind CSS) for ${componentName}. 
ROLE: Sovereign UI/UX Architect.
Pattern Description: ${description}
REQUIREMENT: NO PLACEHOLDERS. NO MOCKS.
The component will be saved in ${componentName}.tsx.`;

        const result = await this.client.call({
            model: 'deepseek-r1:8b',
            prompt: uiPrompt,
            temperature: 0.3
        });

        if (result.ok && result.value.response) {
            let code = result.value.response.replace(/```tsx?/g, '').replace(/```/g, '').trim();
            if (!code.startsWith('import')) code = `import React from 'react';\n${code}`;
            writeFileSync(componentPath, code);
            return ok(`Successfully distilled ${componentName} from neural patterns.`);
        } else if (!result.ok) {
            return result as Result<string>;
        }
        return { ok: false, error: new Error('Model did not return a response for component distillation.') };
    }

    public async forgeSyntheticApp(blueprint: AppBlueprint, targetPath: string): Promise<Result<string>> {
        logger.info({ blueprint, targetPath }, 'Forging Synthetic WebApp project');

        const yaostate = this.hexagram.getYaoState();
        const interpretation = this.hexagram.getInterpretation();

        const systemPrompt = `
You are the Sovereign WebApp Forge. 
Generate a novel, functional Cloudflare Workers Assets (Pages) application codebase.
Combine architectural patterns for AI, D1, and KV into a single cohesive project.

THEME: Sovereign Aesthetic (Glow, Mono fonts, Dark Mode)
COGNITIVE BIAS: ${interpretation.name} (${interpretation.judgment}). Current YaoState: ${yaostate}
BINDINGS REQUIRED: AI, DB (D1), KV

OUTPUT FORMAT: JSON ONLY
{
  "files": {
    "package.json": "string",
    "wrangler.jsonc": "string",
    "src/index.ts": "Worker logic using AI, D1, KV",
    "src/App.tsx": "React Dashboard using Sovereign components",
    "src/index.css": "Tailwind directives",
    "tailwind.config.ts": "Sovereign config"
  }
}
`;

        const res = await this.client.call({
            model: 'deepseek-r1:8b',
            prompt: `${systemPrompt}\n\nProject Prompt: "${blueprint.name}"\nFeatures: ${blueprint.features.join(', ')}`,
            temperature: 0.3
        });

        if (!res.ok) return res;

        try {
            const data = JSON.parse(res.value.response.match(/\{[\s\S]*\}/)?.[0] || '{}');
            if (!data.files) throw new Error('No files generated in synthetic forge');

            if (!existsSync(targetPath)) mkdirSync(targetPath, { recursive: true });

            for (const [path, content] of Object.entries(data.files)) {
                const fullPath = join(targetPath, path as string);
                const dir = dirname(fullPath);
                if (!existsSync(dir)) mkdirSync(dir, { recursive: true });
                writeFileSync(fullPath, content as string);
            }

            // Write POG dots
            writeFileSync(join(targetPath, 'INTENT_MANIFEST.md'),
                `# Intent Manifest: ${blueprint.name} (SYNTHETIC)\n\n` +
                `Forged by POG2 Synthetic Mind.\n\n` +
                `## Features\n${blueprint.features.map(f => `- ${f}`).join('\n')}\n\n` +
                `## Substrate\nComposite Cloudflare (AI + D1 + KV).`
            );

            return ok(targetPath);
        } catch (err) {
            return { ok: false, error: err as Error };
        }
    }

    public async planApp(prompt: string, synthetic = false): Promise<Result<AppBlueprint>> {
        const templates = this.listAvailableTemplates();
        const systemPrompt = `
You are the WebApp Forge Planner. 
Analyze the user prompt and create a technical blueprint for a local project.

MODE: ${synthetic ? 'SYNTHETIC (Create something new/novel)' : 'TEMPLATE (Cloning existing patterns)'}

AVAILABLE CLOUDFLARE TEMPLATES:
${templates.map(t => `- ${t}`).join('\n')}

Respond in JSON ONLY:
{ "name": "string", "features": ["string"], "stack": "react-vite" | "cloudflare-template" | "synthetic", "template": "string", "decision_reasoning": "string" }
`;

        const res = await this.client.call({
            model: 'deepseek-r1:8b',
            prompt: `${systemPrompt}\n\nUser Prompt: "${prompt}"`,
            temperature: 0.2
        });

        if (!res.ok) return res;

        try {
            const data = JSON.parse(res.value.response.match(/\{[\s\S]*\}/)?.[0] || '{}');
            if (synthetic) data.stack = 'synthetic';
            return { ok: true, value: data };
        } catch (err) {
            return { ok: false, error: new Error('App planning failed to parse.') };
        }
    }

    public async healthCheck(): Promise<{ online: boolean; details: string }> {
        const templates = this.listAvailableTemplates();
        const exists = existsSync(this.templatesPath);
        const online = exists && templates.length > 0;
        return {
            online,
            details: `WebApp Forge: ${online ? 'ONLINE' : 'DEGRADED'} (${templates.length} templates primed at ${this.templatesPath})`
        };
    }
}

